-- ------------------------------------------------------------
-- Existing Fare Keralam category mappings.
-- These mappings do not invent fare rules for classifications that
-- are not yet represented by an operational category/fare rule.
-- ------------------------------------------------------------
INSERT INTO government_vehicle_category_map (subclass_id, vehicle_category_id, notes)
SELECT s.id, vc.id, 'Mapped to existing Fare Keralam Auto Rickshaw category.'
FROM government_vehicle_subclasses s
JOIN government_vehicle_classes c ON c.id = s.class_id
JOIN vehicle_categories vc ON vc.name = 'Auto Rickshaw'
WHERE c.name = 'Hire / Contract Carriage' AND s.name = 'Auto Rickshaw'
  AND NOT EXISTS (SELECT 1 FROM government_vehicle_category_map m WHERE m.subclass_id=s.id AND m.vehicle_category_id=vc.id)
ON CONFLICT DO NOTHING;

