INSERT INTO government_vehicle_category_map (configuration_id, vehicle_category_id, notes)
SELECT cfg.id, vc.id, 'Mapped to existing Fare Keralam Traveller category.'
FROM government_vehicle_configurations cfg
JOIN government_vehicle_subclasses s ON s.id=cfg.subclass_id
JOIN government_vehicle_classes c ON c.id=s.class_id
JOIN vehicle_categories vc ON vc.name='Traveller'
WHERE c.name='Hire / Contract Carriage' AND s.name='Contract Carriage' AND cfg.name='Traveller / Contract vehicles'
  AND NOT EXISTS (SELECT 1 FROM government_vehicle_category_map m WHERE m.configuration_id=cfg.id AND m.vehicle_category_id=vc.id)
ON CONFLICT DO NOTHING;

