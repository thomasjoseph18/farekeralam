SELECT id, v.name, v.description, v.display_order
FROM government_vehicle_classes c
CROSS JOIN (VALUES
    ('Auto Rickshaw', 'Three-wheeled passenger auto-rickshaw.', 1),
    ('Quadricycle', 'Quadricycle passenger vehicle classification.', 2),
    ('Motor Cab / Taxi', 'Passenger motor cab / taxi classification.', 3),
    ('Maxicab', 'Passenger vehicle classified as a maxicab.', 4),
    ('Contract Carriage', 'Contract carriage classification.', 5)
) AS v(name, description, display_order)
WHERE c.name = 'Hire / Contract Carriage'
ON CONFLICT (class_id, name) DO UPDATE SET description = EXCLUDED.description, display_order = EXCLUDED.display_order;

