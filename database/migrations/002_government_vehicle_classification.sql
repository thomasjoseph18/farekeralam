-- ============================================================
-- FARE KERALAM - GOVERNMENT VEHICLE CLASSIFICATION
-- Adds the hierarchical government-oriented classification used
-- by the passenger-facing calculator.
-- ============================================================

CREATE TABLE IF NOT EXISTS government_vehicle_classes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    description TEXT,
    display_order INTEGER NOT NULL DEFAULT 0,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS government_vehicle_subclasses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    class_id BIGINT NOT NULL REFERENCES government_vehicle_classes(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    description TEXT,
    display_order INTEGER NOT NULL DEFAULT 0,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (class_id, name)
);

CREATE TABLE IF NOT EXISTS government_vehicle_configurations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subclass_id BIGINT NOT NULL REFERENCES government_vehicle_subclasses(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    description TEXT,
    display_order INTEGER NOT NULL DEFAULT 0,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (subclass_id, name)
);

-- Links a government classification node to the Fare Keralam
-- operational category when a matching fare category exists.
CREATE TABLE IF NOT EXISTS government_vehicle_category_map (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subclass_id BIGINT REFERENCES government_vehicle_subclasses(id) ON DELETE CASCADE,
    configuration_id BIGINT REFERENCES government_vehicle_configurations(id) ON DELETE CASCADE,
    vehicle_category_id BIGINT NOT NULL REFERENCES vehicle_categories(id) ON DELETE RESTRICT,
    notes TEXT,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    CHECK (subclass_id IS NOT NULL OR configuration_id IS NOT NULL)
);

CREATE INDEX IF NOT EXISTS idx_gov_vehicle_subclasses_class
    ON government_vehicle_subclasses(class_id);
CREATE INDEX IF NOT EXISTS idx_gov_vehicle_configurations_subclass
    ON government_vehicle_configurations(subclass_id);
CREATE INDEX IF NOT EXISTS idx_gov_vehicle_category_map_subclass
    ON government_vehicle_category_map(subclass_id);
CREATE INDEX IF NOT EXISTS idx_gov_vehicle_category_map_configuration
    ON government_vehicle_category_map(configuration_id);

